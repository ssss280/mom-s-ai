def _first_hit(text: str, mapping: dict):
    """在文本里找第一个命中的别名（长别名优先，避免"香港"抢在"香港特别行政区"前面）。"""
    for alias in sorted(mapping, key=len, reverse=True):
        if alias.lower() in text.lower():
            return mapping[alias]
    return None


def parse_region_category(query: str):
    """把查询拆成 (地区, 类目)，任一没命中就返回 (None, None)。"""
    text = (query or "").strip()
    if not text:
        return None, None
    return _first_hit(text, REGION_ALIASES), _first_hit(text, CATEGORY_ALIASES)


def suggest_official(query: str) -> dict:
    """根据"地区 + 种类"推断用户可能想搜的官方展会名。

    返回 {} 表示没有把握的建议（宁可不猜）。
    只有地区与类目**都**命中、且该组合有官方展会时才给建议——
    实测用户说"香港照明展"时，官方名是"香港国际秋季灯饰展"，但这个词组本身搜不到，
    换官方名之后第一条就是 HKTDC 官方页。
    """
    region, category = parse_region_category(query)
    if not region or not category:
        return {}
    fair = KNOWN_FAIRS.get((region, category))
    if not fair:
        return {}
    return {
        "region": region,
        "category": category,
        "official": fair["official"],
        "note": fair["note"],
        "related": list(fair.get("related") or []),
    }
